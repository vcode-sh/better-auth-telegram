const AUTH_BASE = `${BASE_URL}/api/auth`;

type AuthOptions = Parameters<typeof betterAuth>[0];

type Row = Record<string, any>;
export interface MemoryDB extends Record<string, Row[]> {
  account: Row[];
  session: Row[];
  user: Row[];
  verification: Row[];
}

function telegramOptions(
  overrides: Partial<TelegramPluginOptions>
): TelegramPluginOptions {
  return { botToken: BOT_TOKEN, botUsername: "test_bot", ...overrides };
}

function baseOptions(
  pluginOptions: Partial<TelegramPluginOptions>,
  authOptions: Partial<AuthOptions>
): AuthOptions {
  return {
    baseURL: BASE_URL,
    secret: "better-auth-telegram-test-secret-0123456789abcdef",
    logger: { disabled: true },
    ...authOptions,
    plugins: [
      telegram(telegramOptions(pluginOptions)),
      ...(authOptions.plugins ?? []),
    ],
  };
}

/** Better Auth on the in-memory adapter. */
export function createMemoryAuth(
  pluginOptions: Partial<TelegramPluginOptions> = {},
  authOptions: Partial<AuthOptions> = {}
) {
  const db: MemoryDB = { user: [], session: [], account: [], verification: [] };
  const auth = betterAuth({
    ...baseOptions(pluginOptions, authOptions),
    database: memoryAdapter(db),
  });
  return { auth, db, client: createClient(auth) };
}

/**
 * Better Auth on SQLite with the schema generated by Better Auth's own
 * migrations, so NOT NULL / UNIQUE constraints and the runtime schema check
 * behave as they do in production SQL databases.
 */
export async function createSqliteAuth(
  pluginOptions: Partial<TelegramPluginOptions> = {},
  authOptions: Partial<AuthOptions> = {}
) {
  const sqlite = new DatabaseSync(":memory:");
  const options = {
    ...baseOptions(pluginOptions, authOptions),
    database: sqlite,
  };
  const { runMigrations } = await getMigrations(options);
  await runMigrations();
  const auth = betterAuth(options);
  const rows = (table: string) =>
    sqlite.prepare(`select * from "${table}"`).all() as Record<string, any>[];
  return { auth, sqlite, rows, client: createClient(auth) };
}

interface Auth {
  handler: (request: Request) => Promise<Response>;
}

/** Minimal cookie-carrying HTTP client for `auth.handler`. */
export function createClient(auth: Auth) {
  const jar = new Map<string, string>();

  const storeCookies = (response: Response) => {
    for (const cookie of response.headers.getSetCookie()) {
      const [pair] = cookie.split(";");
      const index = pair!.indexOf("=");
      const name = pair!.slice(0, index);
      const value = pair!.slice(index + 1);
      if (value === "" || /max-age=0/iu.test(cookie)) {
        jar.delete(name);
      } else {
        jar.set(name, value);
      }
    }
  };

  const cookieHeader = () =>
    [...jar].map(([name, value]) => `${name}=${value}`).join("; ");

  async function request(
    path: string,
    init: {
      method?: string;
      body?: unknown;
      headers?: Record<string, string>;
    } = {}
  ) {
    const url = path.startsWith("http") ? path : `${AUTH_BASE}${path}`;
    const response = await auth.handler(
      new Request(url, {
        method: init.method ?? (init.body === undefined ? "GET" : "POST"),
        headers: {
          origin: BASE_URL,
          ...(init.body === undefined
            ? {}
            : { "content-type": "application/json" }),
          ...(jar.size ? { cookie: cookieHeader() } : {}),
          ...init.headers,
        },
        body: init.body === undefined ? undefined : JSON.stringify(init.body),
      })
    );
    storeCookies(response);
    const text = await response.text();
    let json: any;
    try {
      json = text ? JSON.parse(text) : undefined;
    } catch {
      json = undefined;
    }
    return { status: response.status, headers: response.headers, json, text };
  }

  return {
    request,
    post: (path: string, body: unknown) => request(path, { body }),
    get: (path: string) => request(path),
    clearCookies: () => jar.clear(),
    hasSession: () =>
      [...jar.keys()].some((name) => name.includes("session_token")),
  };
}

export type TestClient = ReturnType<typeof createClient>;

async function hmacHex(key: Uint8Array, data: string) {
  const cryptoKey = await crypto.subtle.importKey(
    "raw",
    key as BufferSource,
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"]
  );
  const signature = await crypto.subtle.sign(
    "HMAC",
    cryptoKey,
    new TextEncoder().encode(data)
  );
  return Buffer.from(signature).toString("hex");
}

/** Login Widget payload signed exactly like Telegram signs it. */
export async function signWidgetData(
  fields: Record<string, string | number> & { id: number },
  botToken = BOT_TOKEN
) {
  const data: Record<string, string | number> = {
    first_name: "Ann",
    auth_date: Math.floor(Date.now() / 1000),
    ...fields,
  };
  const checkString = Object.keys(data)
    .sort()
    .map((key) => `${key}=${data[key]}`)
    .join("\n");
  const secret = createHash("sha256").update(botToken).digest();
  return { ...data, hash: await hmacHex(secret, checkString) };
}

/** Code-unit key order, as Telegram sorts the data-check-string. */
function byCodeUnit([a]: [string, string], [b]: [string, string]) {
  if (a === b) {
    return 0;
  }
  return a < b ? -1 : 1;
}

/** Signs arbitrary initData fields exactly like Telegram signs them. */
export async function signInitParams(
  fields: Record<string, string>,
  botToken = BOT_TOKEN
) {
  const params = new URLSearchParams(fields);
  const checkString = [...params.entries()]
    .sort(byCodeUnit)
    .map(([key, value]) => `${key}=${value}`)
    .join("\n");
  const secret = new Uint8Array(
    Buffer.from(
      await hmacHex(new TextEncoder().encode("WebAppData"), botToken),
      "hex"
    )
  );
  params.set("hash", await hmacHex(secret, checkString));
  return params.toString();
}

/** Mini App initData for `user`, signed exactly like Telegram signs it. */
export function signInitData(
  user: Record<string, unknown> & { id: number },
  extra: Record<string, string> = {},
  botToken = BOT_TOKEN
) {
  return signInitParams(
    {
      auth_date: String(Math.floor(Date.now() / 1000)),
      query_id: "AAHdF6IQAAAAAN0XohDhrOrc",
      user: JSON.stringify({ first_name: "Ann", ...user }),
      ...extra,
    },
    botToken
  );
}

interface PendingAuthorization {
  claims: JWTPayload;
  codeChallenge: string | null;
  forge: boolean;
  nonce: string | null;
  redirectURI: string;
}

export interface AuthorizeOptions {
  /** Sign the ID token with a key that is not in the JWKS. */
  forge?: boolean;
  /** Replace the nonce Telegram would echo (null drops it). */
  nonce?: string | null;
}

/**
 * Fake oauth.telegram.org. Intercepts `fetch` for the token and JWKS
 * endpoints; everything else falls through to the real `fetch`.
 */
export async function mockTelegramOIDC(
  options: {
    clientId?: string;
    clientSecret?: string;
    alg?: "RS256" | "ES256" | "EdDSA";
  } = {}
) {
  const clientId = options.clientId ?? BOT_ID;
  const clientSecret = options.clientSecret ?? "oidc-client-secret";
  const alg = options.alg ?? "RS256";
  const { privateKey, publicKey } = await generateKeyPair(alg, {
    ...(alg === "EdDSA" ? { crv: "Ed25519" } : {}),
  });
  const kid = `test-${alg.toLowerCase()}`;
  const jwk = { ...(await exportJWK(publicKey)), kid, alg, use: "sig" };
  const pending = new Map<string, PendingAuthorization>();
  const tokenRequests: {
    authorization: string | null;
    body: URLSearchParams;
  }[] = [];
  let jwksRequests = 0;
  let codeCounter = 0;

  const realFetch = globalThis.fetch;
  const fetchSpy = vi
    .spyOn(globalThis, "fetch")
    .mockImplementation(async (input, init) => {
      const { url } = new Request(input as RequestInfo);
      if (url.startsWith(TELEGRAM_OIDC_JWKS_URI)) {
        jwksRequests += 1;
        return Response.json({ keys: [jwk] });
      }
      if (url.startsWith(TELEGRAM_OIDC_TOKEN_ENDPOINT)) {
        const request = new Request(input as RequestInfo, init);
        const body = new URLSearchParams(await request.text());
        const authorization = request.headers.get("authorization");
        tokenRequests.push({ authorization, body });
        return Response.json(await tokenResponse(authorization, body));
      }
      return realFetch(input as RequestInfo, init);
    });

  async function sign(
    claims: JWTPayload,
    key: KeyObject | CryptoKey = privateKey
  ) {
    const now = Math.floor(Date.now() / 1000);
    return await new SignJWT({ ...claims })
      .setProtectedHeader({ alg, kid, typ: "JWT" })
      .setIssuer(TELEGRAM_OIDC_ISSUER)
      .setAudience(clientId)
      .setIssuedAt(now)
      .setExpirationTime(now + 30)
      .sign(key);
  }

  async function tokenResponse(
    authorization: string | null,
    body: URLSearchParams
  ) {
    const code = body.get("code") ?? "";
    const authz = pending.get(code);
    // Telegram validates the code before client credentials and answers
    // errors with HTTP 200.
    if (!authz || body.get("redirect_uri") !== authz.redirectURI) {
      return { error: "invalid_grant" };
    }
    const expected = `Basic ${Buffer.from(`${clientId}:${clientSecret}`).toString("base64")}`;
    const postAuth =
      body.get("client_id") === clientId &&
      body.get("client_secret") === clientSecret;
    if (authorization !== expected && !postAuth) {
      return { error: "invalid_client" };
    }
    if (authz.codeChallenge) {
      const verifier = body.get("code_verifier") ?? "";
      const challenge = createHash("sha256")
        .update(verifier)
        .digest("base64url");
      if (challenge !== authz.codeChallenge) {
        return { error: "invalid_grant" };
      }
    }
    pending.delete(code);
    const idToken = await sign(
      { ...authz.claims, ...(authz.nonce ? { nonce: authz.nonce } : {}) },
      authz.forge ? (await generateKeyPair(alg)).privateKey : privateKey
    );
    return {
      access_token: "AAAAAAAAAAAAAAAAAAAAAAAA",
      id_token: idToken,
      token_type: "Bearer",
      expires_in: 30,
      scope: "openid profile",
    };
  }

  /**
   * Simulates the user approving the login in Telegram: returns the callback
   * URL Telegram would redirect the browser to.
   */
  function authorize(
    authorizationURL: string,
    claims: JWTPayload,
    authorizeOptions: AuthorizeOptions = {}
  ) {
    const url = new URL(authorizationURL);
    codeCounter += 1;
    const code = `code-${codeCounter}`;
    const redirectURI = url.searchParams.get("redirect_uri")!;
    pending.set(code, {
      claims,
      codeChallenge: url.searchParams.get("code_challenge"),
      forge: authorizeOptions.forge ?? false,
      nonce:
        authorizeOptions.nonce === undefined
          ? url.searchParams.get("nonce")
          : authorizeOptions.nonce,
      redirectURI,
    });
    const callback = new URL(redirectURI);
    callback.searchParams.set("code", code);
    callback.searchParams.set("state", url.searchParams.get("state")!);
    return callback.href;
  }

  return {
    clientId,
    clientSecret,
    authorize,
    sign,
    tokenRequests,
    get jwksRequests() {
      return jwksRequests;
    },
    restore: () => fetchSpy.mockRestore(),
  };
}

