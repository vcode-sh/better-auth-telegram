import { DatabaseSync } from "node:sqlite";
import { betterAuth } from "better-auth";
import { memoryAdapter } from "better-auth/adapters/memory";
import { getMigrations } from "better-auth/db/migration";
import { telegram } from "../index";
import type { TelegramPluginOptions } from "../types";
import { BASE_URL, BOT_TOKEN } from "./constants";
import { createClient } from "./http-client";

export type AuthOptions = Parameters<typeof betterAuth>[0];

type Row = Record<string, any>;
export interface MemoryDB extends Record<string, Row[]> {
  account: Row[];
  session: Row[];
  user: Row[];
  verification: Row[];
}

function telegramOptions(
  overrides: Partial<TelegramPluginOptions>
): TelegramPluginOptions {
  return { botToken: BOT_TOKEN, botUsername: "test_bot", ...overrides };
}

/** Better Auth options with the plugin, without a database. */
export function baseOptions(
  pluginOptions: Partial<TelegramPluginOptions>,
  authOptions: Partial<AuthOptions>
): AuthOptions {
  return {
    baseURL: BASE_URL,
    secret: "better-auth-telegram-test-secret-0123456789abcdef",
    logger: { disabled: true },
    ...authOptions,
    plugins: [
      telegram(telegramOptions(pluginOptions)),
      ...(authOptions.plugins ?? []),
    ],
  };
}

/**
 * Better Auth on the in-memory adapter. Pass another instance's `db` to get
 * a second "server" on the same data.
 */
export function createMemoryAuth(
  pluginOptions: Partial<TelegramPluginOptions> = {},
  authOptions: Partial<AuthOptions> = {},
  db: MemoryDB = { user: [], session: [], account: [], verification: [] }
) {
  const auth = betterAuth({
    ...baseOptions(pluginOptions, authOptions),
    database: memoryAdapter(db),
  });
  return { auth, db, client: createClient(auth) };
}

/**
 * Better Auth on SQLite with the schema generated by Better Auth's own
 * migrations, so NOT NULL / UNIQUE constraints and the runtime schema check
 * behave as they do in production SQL databases.
 */
export async function createSqliteAuth(
  pluginOptions: Partial<TelegramPluginOptions> = {},
  authOptions: Partial<AuthOptions> = {}
) {
  const sqlite = new DatabaseSync(":memory:");
  const options = {
    ...baseOptions(pluginOptions, authOptions),
    database: sqlite,
  };
  const { runMigrations } = await getMigrations(options);
  await runMigrations();
  const auth = betterAuth(options);
  const rows = (table: string) =>
    sqlite.prepare(`select * from "${table}"`).all() as Record<string, any>[];
  return { auth, sqlite, rows, client: createClient(auth) };
}
